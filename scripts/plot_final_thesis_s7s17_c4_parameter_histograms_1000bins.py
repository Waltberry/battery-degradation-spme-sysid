def infer_model_from_folder_name(name: str) -> str | None:
    m = re.search(r"final_thesis_(S(?:7|17)_C4)_chunk", name)
    if m:
        return m.group(1)
    return None


def infer_chunk_from_folder_name(name: str) -> int | None:
    m = re.search(r"_chunk_(\d+)_", name)
    if m:
        return int(m.group(1))
    return None


def model_sort_key(mid: str) -> int:
    try:
        return MODEL_ORDER.index(str(mid))
    except ValueError:
        return 999


def model_label(mid: str) -> str:
    return MODEL_LABELS.get(str(mid), str(mid))


def savefig(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(path, dpi=280, bbox_inches="tight")
    print("[saved figure]", path)
    plt.close()


def safe_filename(text: str) -> str:
    return (
        str(text)
        .replace("^", "pow")
        .replace("-", "minus")
        .replace("+", "plus")
        .replace("/", "_")
        .replace(" ", "_")
        .replace("(", "")
        .replace(")", "")
        .replace("[", "")
        .replace("]", "")
        .replace("%", "percent")
    )


def relative_error_percent(true_value: float, estimate: float) -> float:
    denom = max(abs(float(true_value)), 1e-15)
    return 100.0 * abs(float(estimate) - float(true_value)) / denom


def finite_values(series: pd.Series) -> np.ndarray:
    x = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    return x[np.isfinite(x)]


def choose_plot_range(x: np.ndarray, low_q: float = 0.01, high_q: float = 0.99) -> tuple[float, float]:
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if len(x) == 0:
        return np.nan, np.nan
    lo = float(np.quantile(x, low_q))
    hi = float(np.quantile(x, high_q))
    if not np.isfinite(lo) or not np.isfinite(hi) or lo == hi:
        lo = float(np.min(x))
        hi = float(np.max(x))
    if lo == hi:
        pad = abs(lo) * 0.01 + 1e-12
        lo -= pad
        hi += pad
    return lo, hi


def get_best_recovered(values: np.ndarray, true_value: float) -> tuple[float, int, float]:
    values = np.asarray(values, dtype=float)
    mask = np.isfinite(values)
    if not np.any(mask):
        return np.nan, -1, np.nan
    finite_vals = values[mask]
    finite_indices = np.where(mask)[0]
    errors = np.array([relative_error_percent(true_value, v) for v in finite_vals])
    j = int(np.argmin(errors))
    return float(finite_vals[j]), int(finite_indices[j]), float(errors[j])


def safe_load_config(config_path: Path) -> dict[str, Any]:
    if not config_path.exists():
        return {}
    try:
        with open(config_path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as exc:
        print("[warn] could not parse config:", config_path, repr(exc))
        return {}


def get_truth_values_from_config(config_path: Path | None) -> dict[str, float]:
    """Return truth values keyed by all_runs column names."""
    truth: dict[str, float] = {}
    payload = safe_load_config(config_path) if config_path is not None else {}

    t = payload.get("truth", {}) if isinstance(payload, dict) else {}

    # Preferred new location from the synthetic S7/S17 runner.
    ptv = t.get("parameter_truth_values", {}) if isinstance(t, dict) else {}
    if isinstance(ptv, dict):
        for k, v in ptv.items():
            try:
                truth[str(k)] = float(v)
            except Exception:
                pass

    # Fallbacks for the main physical parameters.
    fallback_map = {
        "alpha_n_hat": "alpha_n_true",
        "alpha_p_hat": "alpha_p_true",
        "g_n_hat": "g_n_true",
        "g_p_hat": "g_p_true",
        "b_en_hat": "b_en_true",
        "b_ep_hat": "b_ep_true",
        "theta_n0_fixed": "theta_n0_true",
        "theta_p0_fixed": "theta_p0_true",
    }
    for out_col, truth_key in fallback_map.items():
        if out_col not in truth and truth_key in t:
            try:
                truth[out_col] = float(t[truth_key])
            except Exception:
                pass

    if "k_ind_true" in t and isinstance(t["k_ind_true"], list):
        for i, val in enumerate(t["k_ind_true"], start=1):
            truth.setdefault(f"k{i}_hat", float(val))
    if "k_edges_true" in t and isinstance(t["k_edges_true"], list):
        for i, val in enumerate(t["k_edges_true"], start=1):
            truth.setdefault(f"k_edge{i}_hat", float(val))

    beta_true = t.get("beta_true", {}) if isinstance(t, dict) else {}
    if isinstance(beta_true, dict):
        for name, val in beta_true.items():
            safe = str(name).replace("^", "pow").replace("-", "minus").replace(" ", "_")
            try:
                truth.setdefault(f"beta_{safe}", float(val))
            except Exception:
                pass

    return truth


