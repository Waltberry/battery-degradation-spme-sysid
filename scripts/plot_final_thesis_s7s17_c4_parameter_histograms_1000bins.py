for folder in chunk_dirs:
    model_id = infer_model_from_folder_name(folder.name)
    chunk_index = infer_chunk_from_folder_name(folder.name)
    all_path = folder / "all_runs.csv"
    config_path = folder / "config.json"

    df = pd.read_csv(all_path)

    if "model_id" not in df.columns or df["model_id"].isna().all():
        df["model_id"] = model_id
